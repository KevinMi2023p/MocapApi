#!/usr/bin/env bash
# Provision a local Windows VM ("attached VM") that runs Noitom Axis Studio.
#
# The VM owns the Perception Neuron USB/RNDIS transceiver exclusively (see
# attach-usb.sh); Axis Studio streams BVH/Calc frames over unicast UDP/TCP to
# this Linux host, where MocapApi / Mocap Studio / the gr00t bridge consume
# them. Architecture reference: studio/docs/USB_ON_LINUX.md, "Architecture B".
#
# Tested target: Ubuntu 22.04/24.04 x86_64 with KVM. Requires VT-x/AMD-V
# enabled in firmware. Cloud instances without nested virtualization
# (no /dev/kvm) cannot run the VM; use --dry-run there to inspect commands.

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
VM_NAME="axis-studio"
WINDOWS_ISO=""
WINDOWS_ISO_URL=""
WINDOWS_VERSION="win11"          # win10 | win11
MEMORY_MIB=8192
VCPUS=4
DISK_SIZE_GIB=120
IMAGES_DIR="/var/lib/libvirt/images"
VIRTIO_WIN_URL="https://fedorapeople.org/groups/virt/virtio-win/direct-downloads/stable-virtio/virtio-win.iso"
AXIS_INSTALLER=""
AXIS_INSTALLER_URL=""
AXIS_INSTALLER_KIND=""
DOWNLOAD_AXIS_STUDIO_3=0
AXIS_MEDIA=1
AXIS_GUEST_ASSETS_DIR="${SCRIPT_DIR}/windows"
AXIS_MEDIA_STAGING=""
AXIS_SETUP_ISO=""
AXIS_SETUP_ISO_TEMP=""
AXIS_SETUP_ISO_CREATED=0
DOWNLOAD_TEMP_PATH=""
WINDOWS_VM_ISO=""
WINDOWS_VM_ISO_TEMP=""
STAGED_WINDOWS_ISO_CREATED=0
VIRTIO_ISO=""
VIRTIO_ISO_TEMP=""
DISK_PATH=""
DISK_PATH_TEMP=""
DISK_CREATED=0
DOWNLOAD_ONLY=0
DRY_RUN=0
SKIP_PACKAGES=0
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/axis-vm"
MEDIA_CACHE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/axis-vm/downloads"
WINDOWS_11_DOWNLOAD_PAGE="https://www.microsoft.com/software-download/windows11"
WINDOWS_10_DOWNLOAD_PAGE="https://www.microsoft.com/software-download/windows10ISO"
WINDOWS_DOWNLOAD_PAGE="${WINDOWS_11_DOWNLOAD_PAGE}"
NOITOM_DOWNLOAD_PAGE="https://shop.noitom.com.cn/common/product_item/index.jhtml?productItemId=3"
NOITOM_ACCOUNT_PAGE="https://account.noitom.com/"
DEFAULT_AXIS_STUDIO_3_URL="https://cdn.noitom.com/download/Axis%20Studio%203%20%28Anti-Mag%29/Axis_Studio_nacs_x64_3_0_14004_2620_20251222173616363.msi"

