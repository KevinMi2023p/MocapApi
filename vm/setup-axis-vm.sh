  Windows ${WINDOWS_VERSION#win} ISO: ${WINDOWS_DOWNLOAD_PAGE}
  Axis Studio:    ${NOITOM_DOWNLOAD_PAGE}
  Axis account:   ${NOITOM_ACCOUNT_PAGE}

Microsoft's generated ISO links expire after 24 hours. Download the ISO in a
browser and pass its actual path, or paste the fresh direct link with
